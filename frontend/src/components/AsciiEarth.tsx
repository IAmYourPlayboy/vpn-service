const FRAME_COUNT = FRAMES.length
const ROTATION_PERIOD = 30000  // 30 секунд на полный оборот
const FRAME_INTERVAL = Math.round(ROTATION_PERIOD / FRAME_COUNT)

interface Props {
  className?: string
}

export default function AsciiEarth({ className }: Props) {
  const [frameIndex, setFrameIndex] = useState(0)

  useEffect(() => {
    const interval = setInterval(() => {
      setFrameIndex((prev) => (prev + 1) % FRAME_COUNT)
    }, FRAME_INTERVAL)

    return () => clearInterval(interval)
  }, [])

  return (
    <pre
      className={`font-mono text-white/15 text-[10px] leading-[12px] select-none whitespace-pre ${className || ''}`}
      aria-hidden="true"
    >
      {FRAMES[frameIndex]}
    </pre>
  )
}
